import React, { useState } from "react";
import { generatePDF } from "../Staff/staffUtils";

export function RecordsTab({ pastRecords }) {
  const [expandedLogId, setExpandedLogId] = useState(null);

  return (
    <div className="bg-white rounded-xl border shadow-sm overflow-hidden">
      <table className="w-full text-left text-sm">
        <thead className="bg-slate-50 border-b">
          <tr>
            <th className="p-4 text-slate-600 font-bold">Date / ID</th>
            <th className="p-4 text-slate-600 font-bold">Patient Details</th>
            <th className="p-4 text-slate-600 font-bold">Report Generation</th>
            <th className="p-4 text-slate-600 font-bold">Billing &amp; Dues</th>
            <th className="p-4 text-slate-600 font-bold text-right">
              Actions &amp; Logs
            </th>
          </tr>
        </thead>
        <tbody className="divide-y divide-slate-100">
          {pastRecords.length === 0 ? (
            <tr>
              <td colSpan="5" className="p-8 text-center text-slate-400">
                No completed patient records found.
              </td>
            </tr>
          ) : (
            pastRecords.map((b) => {
              const logList = b.downloadLogs || [];
              return (
                <React.Fragment key={b.id}>
                  <tr className="hover:bg-slate-50">
                    <td className="p-4">
                      <span className="block font-bold text-slate-800">
                        {b.date}
                      </span>
                      <span className="text-xs text-slate-500 font-mono">
                        {b.clinicalId}
                      </span>
                    </td>
                    <td className="p-4">
                      <span className="font-bold text-slate-800 block">
                        {b.name}
                      </span>
                      <span className="text-xs text-slate-500">
                        {b.age || "N/A"}Y / {b.gender || "N/A"} |{" "}
                        {b.phone || "Walk-in"}
                      </span>
                    </td>
                    <td className="p-4">
                      {b.reportGenerated ? (
                        <div>
                          <span className="text-xs bg-emerald-100 text-emerald-800 px-2 py-1 rounded font-bold border border-emerald-200 inline-block">
                            ✅ Generated by {b.reportGeneratedBy}
                          </span>
                          <span className="block text-[11px] text-slate-500 mt-1">
                            Downloaded {logList.length} time(s)
                          </span>
                        </div>
                      ) : (
                        <span className="text-xs bg-amber-100 text-amber-800 px-2 py-1 rounded font-bold border border-amber-200">
                          ⏳ Locked (Not Downloaded Yet)
                        </span>
                      )}
                    </td>
                    <td className="p-4">
                      <span className="font-extrabold text-slate-800 block">
                        Total: ₹{b.total}
                      </span>
                      <span className="text-xs text-slate-500 block">
                        Cash: ₹{b.cashPaid || 0} | UPI: ₹{b.upiPaid || 0}
                      </span>
                      {Number(b.balanceDue || 0) > 0 && (
                        <span className="text-xs font-bold text-red-600">
                          Due: ₹{b.balanceDue}
                        </span>
                      )}
                    </td>
                    <td className="p-4 text-right space-x-2">
                      <button
                        onClick={() =>
                          generatePDF(
                            b,
                            b.tests || [],
                            b.results || {},
                            true
                          )
                        }
                        className="text-xs font-bold px-3 py-1.5 rounded bg-slate-800 text-white hover:bg-slate-900"
                      >
                        PDF
                      </button>
                      <button
                        onClick={() =>
                          setExpandedLogId(expandedLogId === b.id ? null : b.id)
                        }
                        className="text-xs font-bold px-3 py-1.5 rounded border bg-white hover:bg-slate-100"
                      >
                        {expandedLogId === b.id ? "Hide Logs" : "Audit Trail"}
                      </button>
                    </td>
                  </tr>

                  {expandedLogId === b.id && (
                    <tr className="bg-slate-50">
                      <td colSpan="5" className="p-4 border-l-4 border-l-slate-800">
                        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                          <div>
                            <h4 className="text-xs font-bold text-slate-500 mb-2">
                              MODIFICATION &amp; ACTION HISTORY
                            </h4>
                            <ul className="space-y-1">
                              {b.history && b.history.length > 0 ? (
                                b.history.map((h, i) => (
                                  <li key={i} className="text-xs text-slate-700">
                                    <span className="font-bold text-slate-900">
                                      {h.action}
                                    </span>{" "}
                                    by <span className="italic">{h.by}</span> on{" "}
                                    {new Date(h.time).toLocaleString()}
                                  </li>
                                ))
                              ) : (
                                <li className="text-xs text-slate-400">
                                  No history recorded.
                                </li>
                              )}
                            </ul>
                          </div>

                          <div>
                            <h4 className="text-xs font-bold text-slate-500 mb-2">
                              PDF DOWNLOAD TRACKING ({logList.length} Downloads)
                            </h4>
                            <ul className="space-y-1">
                              {logList.length > 0 ? (
                                logList.map((log, i) => (
                                  <li key={i} className="text-xs text-slate-700">
                                    <span className="font-bold text-emerald-700">
                                      Download #{i + 1}
                                    </span>{" "}
                                    by <span className="italic">{log.by}</span>{" "}
                                    on {new Date(log.time).toLocaleString()}
                                  </li>
                                ))
                              ) : (
                                <li className="text-xs text-slate-400">
                                  File has never been downloaded.
                                </li>
                              )}
                            </ul>
                          </div>
                        </div>
                      </td>
                    </tr>
                  )}
                </React.Fragment>
              );
            })
          )}
        </tbody>
      </table>
    </div>
  );
}
